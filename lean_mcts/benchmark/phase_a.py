FEWSHOT_DEFAULT = Path("sprint/benchmark/results/phase_a_fewshot.json")


def load_fewshot(path: Path) -> list[dict]:
    data = json.loads(path.read_text())
    return data["pairs"]


def build_goal_state(task) -> str:
    """Lean-style goal state from a SynthesisTask's metadata.

    Mirrors what the Pantograph daemon shows after auto-intro.
    """
    if getattr(task, "params_signature", None):
        # Multi-arg: `(pivot : Int) (xs : List Int)` → two hypothesis lines
        parts = re.findall(r"\(([^:]+)\s*:\s*([^)]+)\)", task.params_signature)
        hyps = []
        for names, ty in parts:
            for name in names.strip().split():
                hyps.append(f"{name} : {ty.strip()}")
        return "\n".join(hyps) + f"\n⊢ {task.return_type}"
    else:
        return f"xs : {task.input_type}\n⊢ {task.return_type}"


def build_prompt(fewshot: list[dict], task) -> str:
    """Completion-style few-shot prompt for base Qwen."""
    parts = [
        "You are an expert Lean 4 programmer. Given a tactic goal state, "
        "produce a single tactic body that solves it. Use `exact` with a "
        "complete term. Only output the tactic — no commentary, no "
        "surrounding `by` block.",
        "",
    ]
    for pair in fewshot:
        parts.append("Goal:")
        parts.append(pair["state"])
        parts.append("Tactic:")
        parts.append(pair["tactic"])
        parts.append("")
    parts.append("Goal:")
    parts.append(build_goal_state(task))
    parts.append("Tactic:")
    return "\n".join(parts)


def load_local_model(model_id: str):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer

    tokenizer = AutoTokenizer.from_pretrained(model_id, trust_remote_code=True)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    model = AutoModelForCausalLM.from_pretrained(
        model_id, torch_dtype=torch.bfloat16, trust_remote_code=True,
    )
    model.to("cuda")
    model.eval()
    return model, tokenizer


def generate_local(model, tokenizer, prompt: str, n: int, temperature: float,
                   max_new_tokens: int = 256) -> list[str]:
    import torch

    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
    prompt_len = inputs["input_ids"].shape[1]
    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            num_return_sequences=n,
            do_sample=True,
            temperature=temperature,
            top_p=0.95,
            pad_token_id=tokenizer.eos_token_id,
        )
    tactics = []
    for seq in outputs:
        text = tokenizer.decode(seq[prompt_len:], skip_special_tokens=True)
        # Drop leading whitespace BEFORE scanning for stop tokens — otherwise
        # a model that starts with a blank line gets truncated to the empty
        # string by the "\n\n" rule. Phase B retrieval prompts trigger this
        # on Qwen-1.5B for several tasks (eats 8 samples → 0 unique).
        text = text.lstrip()
        for stop in ["\nGoal:", "\n---"]:
            idx = text.find(stop)
            if idx != -1:
                text = text[:idx]
        # Cut at the first BLANK LINE BREAK (empty line after real content).
        # This still prevents the model from continuing into a new pair,
        # but tolerates a leading newline in the model's output.
        lines = text.split("\n")
        cut = None
        for i in range(1, len(lines)):
            if lines[i].strip() == "" and lines[i - 1].strip() != "":
                cut = i
                break
        if cut is not None:
            text = "\n".join(lines[:cut])
        tactic = text.strip()
        if tactic:
            tactics.append(tactic)
    # De-dup while preserving order
    return list(dict.fromkeys(tactics))


def verify_task(task, tactics: list[str], client, verbose: bool = False) -> list[dict]:
    """Oracle-verify each tactic candidate independently."""
    from lean_mcts.eval.oracle import daemon_warm_verify

    results = []
    for i, tactic in enumerate(tactics):
        try:
            r = daemon_warm_verify(task, [tactic], client, verbose=False)
            results.append({
                "tactic": tactic,
                "passed": r.passed,
                "n_passed": r.n_passed,
                "n_total": r.n_total,
                "error": r.error,
            })
            if verbose:
                marker = "PASS" if r.passed else "FAIL"
                print(f"    [{marker}] #{i} {tactic[:80]}")
        except Exception as e:
            results.append({
                "tactic": tactic,
                "passed": False,
                "n_passed": 0,
                "n_total": len(task.test_cases),
                "error": f"verify crash: {e}",
            })
            if verbose:
                print(f"    [CRASH] #{i} {e}")
    return results


def summarize(per_task: list[dict]) -> dict:
    solved = sum(1 for t in per_task if any(r["passed"] for r in t["candidates"]))
    total = len(per_task)
    return {
        "solved": solved,
        "total": total,
        "solve_rate": round(solved / total, 3) if total else 0.0,
        "solved_tasks": [t["name"] for t in per_task if any(r["passed"] for r in t["candidates"])],
    }


