def format_test_case_line(task, tc: dict) -> str:
    """Same rendering as phase_a_ollama.format_test_case (all input args)."""
    from lean_mcts.benchmark.phase_a_ollama import format_test_case
    return format_test_case(task, tc)


def build_spec_block(task, n_tests: int = 3) -> list[str]:
    """Task name / description / theorem name / first-N tests — the same
    information phase_a_ollama.build_messages gives the Ollama model."""
    lines = [
        f"Task: {task.name}",
        f"Description: {task.description}",
        f"Theorem name: {task.theorem_name}",
        f"Test cases (first {min(n_tests, len(task.test_cases))} shown):",
    ]
    for tc in task.test_cases[:n_tests]:
        lines.append(format_test_case_line(task, tc))
    return lines


def build_spec_prompt(fewshot: list[dict], task, n_tests: int = 3) -> str:
    """Completion-style prompt carrying task name, description and 3 tests
    in addition to the goal state (same 5-pair few-shot as build_prompt).

    Completion (not chat) format: the Qwen2.5-Coder 1.5B/7B checkpoints are
    base models; their tokenizer ships the generic Qwen chat template but
    the weights are not instruction-tuned.
    """
    parts = [
        "You are an expert Lean 4 programmer. Given a task description, "
        "example test cases and a tactic goal state, produce a single tactic "
        "body that solves it. Use `exact` with a complete term. Only output "
        "the tactic — no commentary, no surrounding `by` block.",
        "",
    ]
    for pair in fewshot:
        parts.append("Goal:")
        parts.append(pair["state"])
        parts.append("Tactic:")
        parts.append(pair["tactic"])
        parts.append("")
    parts.extend(build_spec_block(task, n_tests))
    parts.append("Goal:")
    parts.append(build_goal_state(task))
    parts.append("Tactic:")
    return "\n".join(parts)


def extract_tactic(text: str, extra_stops: tuple[str, ...] = ()) -> str:
    """The exact extraction rule of generate_local, applied to one sample.
    extra_stops are applied in addition to the original stop strings."""
    text = text.lstrip()
    for stop in ["\nGoal:", "\n---", *extra_stops]:
        idx = text.find(stop)
        if idx != -1:
            text = text[:idx]
    lines = text.split("\n")
    cut = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "" and lines[i - 1].strip() != "":
            cut = i
            break
    if cut is not None:
        text = "\n".join(lines[:cut])
    return text.strip()


def generate_local_raw(model, tokenizer, prompt: str, n: int, temperature: float,
                       max_new_tokens: int = 256,
                       extra_stops: tuple[str, ...] = (),
                       extractor=None) -> list[dict]:
    """Like generate_local but returns every sample: raw decoded text,
    extracted tactic, and whether generation hit max_new_tokens. No dedup."""
    import torch

    inputs = tokenizer(prompt, return_tensors="pt").to(model.device)
    prompt_len = inputs["input_ids"].shape[1]
    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=max_new_tokens,
            num_return_sequences=n,
            do_sample=True,
            temperature=temperature,
            top_p=0.95,
            pad_token_id=tokenizer.eos_token_id,
        )
    samples = []
    for seq in outputs:
        gen = seq[prompt_len:]
        n_tok = int((gen != tokenizer.eos_token_id).sum().item())
        raw = tokenizer.decode(gen, skip_special_tokens=True)
        ext = extractor(raw) if extractor else extract_tactic(raw, extra_stops)
        samples.append({"raw": raw, "extracted": ext,
                        "hit_max_tokens": n_tok >= max_new_tokens})
    return samples


def dedup_extracted(samples: list[dict]) -> list[str]:
    return list(dict.fromkeys(s["extracted"] for s in samples if s["extracted"]))


def classify_verdict(r: dict) -> str:
    if r["passed"]:
        return "pass"
    err = r.get("error") or ""
    if err.startswith("verify crash") or "check_compile failed" in err:
        return "infra_error"
    if err:
        return "compile_fail"
    return "wrong_output"


class VerifyPool:
    """Single-candidate verification (daemon_warm_verify: one definition
    per check_compile) spread over a few verify-pool sockets, with a cache
    keyed by (theorem_name, tactic, test-case set)."""

    def __init__(self, n_workers: int = 3, manifest="/tmp/pantograph_workers.json"):
        import threading
        from lean_mcts.env.pantograph_client import PantographClient
        socks = json.loads(Path(manifest).read_text()).get("verify") or [None]
        self.clients = [PantographClient(s) if s else PantographClient()
                        for s in socks[:n_workers]]
        self.locks = [threading.Lock() for _ in self.clients]
        self.cache: dict = {}
        self._rr = 0
        self._rr_lock = threading.Lock()

    def ping(self) -> bool:
        return all(c.ping() for c in self.clients)

    def _one(self, task, tactic: str) -> dict:
        from lean_mcts.eval.oracle import daemon_warm_verify
        key = (task.theorem_name, task.return_type,
               getattr(task, "params_signature", None), tactic,
               json.dumps(task.test_cases, sort_keys=True))
        if key in self.cache:
            return self.cache[key]
        with self._rr_lock:
            i = self._rr % len(self.clients)
            self._rr += 1
        with self.locks[i]:
            try:
                r = daemon_warm_verify(task, [tactic], self.clients[i])
                out = {"tactic": tactic, "passed": r.passed,
                       "n_passed": r.n_passed, "n_total": r.n_total,
                       "error": r.error,
                       "details": [{"actual": d["actual"], "expected": d["expected"],
                                    "passed": d["passed"]} for d in r.details]}
            except Exception as e:
                out = {"tactic": tactic, "passed": False, "n_passed": 0,
                       "n_total": len(task.test_cases),
                       "error": f"verify crash: {e}", "details": []}
        out["verdict"] = classify_verdict(out)
        self.cache[key] = out
        return out

    def verify_many(self, jobs: list[tuple]) -> list[dict]:
        """jobs: [(task, tactic)] → results in order."""
        from concurrent.futures import ThreadPoolExecutor
        with ThreadPoolExecutor(max_workers=len(self.clients)) as ex:
            return list(ex.map(lambda j: self._one(*j), jobs))


def load_extra_tests(path: Path) -> dict | None:
    if not path.exists():
        return None
    data = json.loads(path.read_text())
    if isinstance(data, dict) and "tasks" in data and isinstance(data["tasks"], dict):
        data = data["tasks"]
    out = {}
    for k, v in data.items():
        if isinstance(v, dict):
            v = v.get("extra_tests") or v.get("test_cases") or v.get("tests") or []
        if isinstance(v, list):
            out[k] = v
    return out


def run_rerun(args):
    """Re-run mode: prompt-style choice, raw generations saved, verification
    via VerifyPool, failure breakdown, optional extra tests."""
    import dataclasses
    import torch

    fewshot = load_fewshot(Path(args.fewshot))
    tasks = list(get_tasks(args.tier))
    print(f"[phase_a/rerun] tier={args.tier} tasks={len(tasks)} style={args.prompt_style} "
          f"T={args.temperature} n={args.n} model={args.model}")
    model, tokenizer = load_local_model(args.model)
    gen = {}
    t0 = time.time()
    for task in tasks:
        if args.prompt_style == "spec":
            prompt = build_spec_prompt(fewshot, task)
            stops = ("\nTask:",)
        else:
            prompt = build_prompt(fewshot, task)
            stops = ()
        samples = generate_local_raw(model, tokenizer, prompt, n=args.n,
                                     temperature=args.temperature, extra_stops=stops)
        # Also record what the ORIGINAL extractor would have kept (goal_only).
        gen[task.name] = {"prompt": prompt, "samples": samples,
                          "unique": dedup_extracted(samples)}
        print(f"  {task.name:<28} {len(gen[task.name]['unique'])} unique")
    wall_gen = time.time() - t0
    del model
    torch.cuda.empty_cache()

    # Save raw generations before verification.
    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    raw_path = out_path.with_suffix(".generations.json")
    raw_path.write_text(json.dumps(gen, indent=1))

    pool = VerifyPool(n_workers=args.verify_workers)
    if not pool.ping():
        print("error: daemon ping failed", file=sys.stderr)
        sys.exit(3)
    extra = load_extra_tests(Path(args.extra_tests)) if args.extra_tests else None
    t0 = time.time()
    per_task = []
    for task in tasks:
        cands = gen[task.name]["unique"]
        res = pool.verify_many([(task, c) for c in cands])
        row = {
            "name": task.name, "theorem_name": task.theorem_name,
            "solved": any(r["passed"] for r in res),
            "n_samples": len(gen[task.name]["samples"]),
            "n_empty_extracted": sum(1 for s in gen[task.name]["samples"] if not s["extracted"]),
            "n_hit_max_tokens": sum(1 for s in gen[task.name]["samples"] if s["hit_max_tokens"]),
            "n_candidates": len(cands),
            "verdict_counts": {v: sum(1 for r in res if r["verdict"] == v)
                               for v in ("pass", "compile_fail", "wrong_output", "infra_error")},
            "candidates": res,
        }
        if extra is not None:
            ext_tcs = extra.get(task.name, [])
            t2 = dataclasses.replace(task, test_cases=list(task.test_cases) + list(ext_tcs))
            passing = [c for c, r in zip(cands, res) if r["passed"]]
            res2 = pool.verify_many([(t2, c) for c in passing])
            row["n_extra_tests"] = len(ext_tcs)
            row["solved_with_extra"] = any(r["passed"] for r in res2)
            row["extra_results"] = res2
        per_task.append(row)
        print(f"  [{'PASS' if row['solved'] else 'fail'}] {task.name:<28} {row['verdict_counts']}")
    wall_ver = time.time() - t0
    summary = summarize(per_task)
    summary["verdict_totals"] = {v: sum(t["verdict_counts"][v] for t in per_task)
                                 for v in ("pass", "compile_fail", "wrong_output", "infra_error")}
    summary["unique_per_task"] = {t["name"]: t["n_candidates"] for t in per_task}
    if extra is not None:
        summary["solved_with_extra"] = sum(1 for t in per_task if t.get("solved_with_extra"))
        summary["solved_with_extra_tasks"] = [t["name"] for t in per_task if t.get("solved_with_extra")]
    else:
        summary["extra_tests"] = "not available at verification time"
    out_path.write_text(json.dumps({
        "config": {"tier": args.tier, "model": args.model, "prompt_style": args.prompt_style,
                   "fewshot": args.fewshot, "n": args.n, "temperature": args.temperature,
                   "top_p": 0.95, "max_new_tokens": 256, "format": "completion",
                   "extra_tests": args.extra_tests if extra is not None else None,
                   "generations_file": str(raw_path),
                   "wall_generate": round(wall_gen, 1), "wall_verify": round(wall_ver, 1)},
        "summary": summary, "per_task": per_task,
    }, indent=2))
    print(f"[phase_a/rerun] solved={summary['solved']}/{summary['total']} "
          f"{summary['solved_tasks']} totals={summary['verdict_totals']} -> {out_path}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--prompt-style", choices=["goal_only", "spec"], default=None,
                        help="(2026-11-21 re-run mode) goal_only = original prompt, "
                             "spec = + task name/description/3 tests. Enables raw "
                             "generation saving and failure breakdown.")
    parser.add_argument("--extra-tests", default=None,
                        help="(re-run mode) optional JSON of extra test cases per task")
    parser.add_argument("--verify-workers", type=int, default=3)
    parser.add_argument("--model", default=None,
                        help="HF model ID for local generation mode.")
    parser.add_argument("--tactics-json", default=None,
                        help="JSON with pre-generated {task_name: [tactics]} "
                             "for frontier mode.")
    parser.add_argument("--fewshot", default=str(FEWSHOT_DEFAULT),
                        help="Frozen few-shot set JSON (default: phase_a_fewshot.json)")
    parser.add_argument("--tier", default="held_out_12",
                        help="Task tier (default: held_out_12)")
    parser.add_argument("--n", type=int, default=8,
                        help="Candidates per task (default: 8)")
    parser.add_argument("--temperature", type=float, default=0.2,
                        help="Sampling temperature (default: 0.2)")
    parser.add_argument("--out", required=True, help="JSON output path")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args()

    if args.prompt_style:
        if not args.model:
            print("error: --prompt-style requires --model", file=sys.stderr)
            sys.exit(2)
        run_rerun(args)
        return

    if bool(args.model) == bool(args.tactics_json):
        print("error: exactly one of --model or --tactics-json is required",
              file=sys.stderr)
        sys.exit(2)

    fewshot = load_fewshot(Path(args.fewshot))
    tasks = list(get_tasks(args.tier))
    print(f"[phase_a] tier={args.tier} tasks={len(tasks)} fewshot_pairs={len(fewshot)}")

    # Load/prepare generation
    tactics_by_task: dict[str, list[str]]
    if args.model:
        print(f"[phase_a] loading local model: {args.model}")
        model, tokenizer = load_local_model(args.model)
        tactics_by_task = {}
        t0_gen = time.time()
        for task in tasks:
            prompt = build_prompt(fewshot, task)
            cands = generate_local(model, tokenizer, prompt,
                                   n=args.n, temperature=args.temperature)
            tactics_by_task[task.name] = cands
            print(f"  {task.name:<28} {len(cands)} unique candidates")
        wall_gen = time.time() - t0_gen
        print(f"[phase_a] generation wall: {wall_gen:.1f}s")
    else:
        print(f"[phase_a] loading pre-generated tactics: {args.tactics_json}")
        tactics_by_task = json.loads(Path(args.tactics_json).read_text())
        wall_gen = 0.0

    # Connect to daemon for oracle verification
    print(f"[phase_a] connecting to daemon for oracle verification")
    from lean_mcts.env.pantograph_client import PantographClient
    client = PantographClient()
    if not client.ping():
        print("error: daemon ping failed; is it running?", file=sys.stderr)
        sys.exit(3)

    # Verify each task's candidates
    print(f"[phase_a] verifying {sum(len(c) for c in tactics_by_task.values())} tactics")
    t0_ver = time.time()
    per_task = []
    for task in tasks:
        cands = tactics_by_task.get(task.name, [])
        results = verify_task(task, cands, client, verbose=args.verbose)
        task_solved = any(r["passed"] for r in results)
        per_task.append({
            "name": task.name,
            "theorem_name": task.theorem_name,
            "lean_file": task.lean_file,
            "solved": task_solved,
            "n_candidates": len(cands),
            "candidates": results,
        })
        marker = "PASS" if task_solved else "fail"
        print(f"  [{marker}] {task.name:<28} {sum(r['passed'] for r in results)}/{len(results)}")
    wall_ver = time.time() - t0_ver

    summary = summarize(per_task)

    config = {
        "tier": args.tier,
        "model": args.model,
        "tactics_json": args.tactics_json,
        "fewshot": str(FEWSHOT_DEFAULT),
        "n": args.n,
        "temperature": args.temperature,
        "wall_generate": round(wall_gen, 1),
        "wall_verify": round(wall_ver, 1),
    }

    out_path = Path(args.out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps({
        "config": config,
        "summary": summary,
        "per_task": per_task,
    }, indent=2))

    print()
    print("=" * 64)
    print(f"Phase A run complete")
    print(f"  model={args.model or '<frontier>'}")
    print(f"  solved={summary['solved']}/{summary['total']}  "
          f"rate={summary['solve_rate']:.1%}")
    print(f"  solved_tasks: {summary['solved_tasks']}")
    print(f"  wall_generate={wall_gen:.1f}s wall_verify={wall_ver:.1f}s")
    print(f"  output={out_path}")
    print("=" * 64)

    sys.exit(0)


if __name__ == "__main__":
    main()
