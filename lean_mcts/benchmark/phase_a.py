"""S30 Phase A — Zero-shot Capability Probe.

Runs a base model (no LoRA, no MCTS, no skeleton search) against the
12 held_out_12 tasks with a frozen generic few-shot preamble, generates
N candidates per task at temperature T, and oracle-verifies each via
the Pantograph daemon. Reports pass@N per task and overall solve count.

Two modes:
  --model PATH        load a local HF checkpoint (Qwen-1.5B / Qwen-7B),
                      generate tactics via transformers, then verify.
  --tactics-json PATH skip generation; load a JSON file of
                      pre-generated tactics keyed by task name. Used
                      for frontier model runs where the parent turn
                      drives generation via the Agent tool.

The few-shot preamble is frozen at
`sprint/benchmark/results/phase_a_fewshot.json` (5 hand-curated pairs
covering let_rec, match_list, foldl accumulator, method_chain, two-list
filter). Same set is reused for all 12 tasks and all 3 Phase A runs.

Usage:
    # Run 1 — Qwen-1.5B base
    python -m lean_mcts.benchmark.phase_a \\
        --model Qwen/Qwen2.5-Coder-1.5B \\
        --out sprint/benchmark/results/phase_a_qwen_1.5b.json

    # Run 2 — Qwen-7B base
    python -m lean_mcts.benchmark.phase_a \\
        --model Qwen/Qwen2.5-Coder-7B \\
        --out sprint/benchmark/results/phase_a_qwen_7b.json

    # Run 3 — frontier (tactics pre-generated by caller via Agent tool)
    python -m lean_mcts.benchmark.phase_a \\
        --tactics-json sprint/benchmark/results/phase_a_frontier_tactics.json \\
        --out sprint/benchmark/results/phase_a_frontier.json
"""

