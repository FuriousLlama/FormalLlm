"""Phase 2a: Generate synthesis tasks from enumerated expressions.

Reads expressions.jsonl and produces:
  1. FormalNav/FormalNav/SynthTasks.lean — Lean file with `by sorry` defs
  2. synth/synth_tasks.jsonl — Python-loadable task definitions with test cases

Usage:
    python synth/task_generator.py \
        --expressions synth/expressions.jsonl \
        --output-lean env/FormalNav/FormalNav/SynthTasks.lean \
        --output-tasks synth/synth_tasks.jsonl \
        --n-tasks 200
"""

from __future__ import annotations

import argparse
import json
import random
import re
import subprocess
from pathlib import Path


# Extra test inputs beyond what enumerate.py used — ensures test cases
# are partially unseen during self-play (tests on novel inputs)
EXTRA_TEST_INPUTS = [
    "[10, -10, 5, -5, 0]",
    "[7]",
    "[-1, 0, 1]",
    "[4, 3, 2, 1]",
    "[0, 0, 0]",
]

LEAN_HEADER = """\
import Mathlib.Tactic
import Mathlib.Data.List.Sort
import Mathlib.Data.List.Basic
import Mathlib.Data.Int.Basic

set_option linter.unusedVariables false

/-!
# Generated Synthesis Tasks for Self-Play

Auto-generated by synth/task_generator.py from enumerated expressions.
Each `def` starts with goal `xs : List Int ⊢ <ReturnType>`.
MCTS fills in the body with `exact <expr>`.
-/

"""

# Regex for Lean diagnostic lines
_DIAG_RE = re.compile(r"^.*\.lean:\d+:\d+:|^note:|^warning:")


def load_expressions(path: Path) -> list[dict]:
    """Load validated expressions from JSONL."""
    exprs = []
    with open(path) as f:
        for line in f:
            exprs.append(json.loads(line))
    return exprs


def select_tasks(
    expressions: list[dict],
    n_tasks: int,
    seed: int = 42,
) -> list[dict]:
    """Select a diverse subset of expressions as tasks.

    Strategy: ensure coverage across return types, base functions, and levels,
    then fill remaining slots randomly.
    """
    rng = random.Random(seed)

    # Group by return type
    by_type: dict[str, list[dict]] = {}
    for e in expressions:
        rt = e["return_type"]
        by_type.setdefault(rt, []).append(e)

    selected: list[dict] = []
    selected_tags: set[str] = set()

    # Guarantee minimum representation per return type
    for rt, group in sorted(by_type.items()):
        n_from_type = max(3, len(group) * n_tasks // len(expressions))
        n_from_type = min(n_from_type, len(group))
        sample = rng.sample(group, n_from_type)
        for e in sample:
            if e["tag"] not in selected_tags:
                selected.append(e)
                selected_tags.add(e["tag"])

    # Fill remaining slots
    remaining = [e for e in expressions if e["tag"] not in selected_tags]
    rng.shuffle(remaining)
    for e in remaining:
        if len(selected) >= n_tasks:
            break
        selected.append(e)
        selected_tags.add(e["tag"])

    return selected[:n_tasks]


def eval_extra_inputs(
    expressions: list[dict],
    lean_project: Path,
    extra_inputs: list[str],
    batch_size: int = 50,
    timeout: int = 120,
) -> dict[str, dict[str, str]]:
    """Evaluate expressions on extra test inputs to get ground truth.

    Returns: {tag: {input: output, ...}, ...}
    """
    results: dict[str, dict[str, str]] = {}
    lean_project = lean_project.resolve()

    for batch_start in range(0, len(expressions), batch_size):
        batch = expressions[batch_start:batch_start + batch_size]

        lines = [
            "import Mathlib.Tactic\n"
            "import Mathlib.Data.List.Sort\n"
            "import Mathlib.Data.List.Basic\n"
            "import Mathlib.Data.Int.Basic\n\n"
            "set_option linter.unusedVariables false\n"
        ]

        for i, expr in enumerate(batch):
            fn = f"_tg_{i}"
            lines.append(f"def {fn} (xs : {expr['input_type']}) : {expr['return_type']} :=")
            lines.append(f"  {expr['expr']}\n")
            for inp in extra_inputs:
                lines.append(f"#eval {fn} {inp}")
            lines.append("")

        eval_file = lean_project / "FormalNav" / "_TaskGen.lean"
        try:
            eval_file.write_text("\n".join(lines))
            result = subprocess.run(
                ["lake", "env", "lean", str(eval_file)],
                cwd=str(lean_project),
                capture_output=True,
                text=True,
                timeout=timeout,
            )

            if result.returncode == 0:
                output_lines = [
                    line.strip()
                    for line in result.stdout.strip().split("\n")
                    if line.strip() and not _DIAG_RE.match(line)
                ]

                n_extra = len(extra_inputs)
                for i, expr in enumerate(batch):
                    start = i * n_extra
                    end = start + n_extra
                    if end <= len(output_lines):
                        outputs = {}
                        for j, inp in enumerate(extra_inputs):
                            outputs[inp] = output_lines[start + j]
                        results[expr["tag"]] = outputs

        except subprocess.TimeoutExpired:
            pass
        finally:
            if eval_file.exists():
                eval_file.unlink()

    return results


def _make_lean_name(tag: str) -> str:
    """Convert a tag like 'filter_gt0_length' to a valid Lean name like 'synthFilterGt0Length'."""
    parts = tag.split("_")
    camel = "synth" + "".join(p.capitalize() for p in parts)
    return camel


def generate_lean_file(tasks: list[dict]) -> str:
    """Generate the SynthTasks.lean file content."""
    lines = [LEAN_HEADER]

    for i, task in enumerate(tasks):
        lean_name = _make_lean_name(task["tag"])
        ret_type = task["return_type"]
        inp_type = task["input_type"]

        lines.append(f"-- Task S{i+1}: {task['tag']} (Level {task['level']})")
        lines.append(f"def {lean_name} (xs : {inp_type}) : {ret_type} := by sorry")
        lines.append("")

    # Reference solutions
    lines.append("/-! ## Reference solutions -/\n")
    for i, task in enumerate(tasks):
        lean_name = _make_lean_name(task["tag"])
        ret_type = task["return_type"]
        inp_type = task["input_type"]
        expr = task["expr"]

        lines.append(f"def {lean_name}_ref (xs : {inp_type}) : {ret_type} :=")
        lines.append(f"  {expr}")
        lines.append("")

    return "\n".join(lines)


def generate_task_jsonl(
    tasks: list[dict],
    extra_outputs: dict[str, dict[str, str]],
) -> list[dict]:
    """Generate task definitions with test cases."""
    task_defs = []

    for i, task in enumerate(tasks):
        lean_name = _make_lean_name(task["tag"])

        # Build test cases from enumeration outputs + extra outputs
        test_cases = []
        for inp, expected in task["outputs"].items():
            test_cases.append({"input": inp, "expected": expected})

        # Add extra test cases if available
        if task["tag"] in extra_outputs:
            for inp, expected in extra_outputs[task["tag"]].items():
                test_cases.append({"input": inp, "expected": expected})

        task_def = {
            "name": f"synth_{task['tag']}",
            "lean_file": "FormalNav/SynthTasks.lean",
            "theorem_name": lean_name,
            "description": f"Synthesize: {task['expr']}",
            "test_cases": test_cases,
            "category": _categorize(task),
            "return_type": task["return_type"],
            "input_type": task["input_type"],
            "level": task["level"],
            "reference_tactic": task["tactic"],
        }
        task_defs.append(task_def)

    return task_defs


def _categorize(expr: dict) -> str:
    """Infer a category from the expression tag."""
    tag = expr["tag"]
    if "foldl" in tag:
        return "fold"
    if "length" in tag:
        return "count"
    if "filter" in tag and "map" in tag:
        return "filter_map"
    if "filter" in tag:
        return "filter"
    if "map" in tag:
        return "map"
    if "mergeSort" in tag:
        return "sort"
    if "takeWhile" in tag or "dropWhile" in tag:
        return "scan"
    if "scanl" in tag:
        return "accumulator"
    if "reverse" in tag:
        return "pipeline"
    if "eraseDups" in tag:
        return "dedup"
    if "take" in tag or "drop" in tag:
        return "slice"
    return "other"


def main():
    parser = argparse.ArgumentParser(description="Generate synthesis tasks from enumerated expressions")
    parser.add_argument("--expressions", type=str, default="synth/expressions.jsonl")
    parser.add_argument("--output-lean", type=str, default="env/FormalNav/FormalNav/SynthTasks.lean")
    parser.add_argument("--output-tasks", type=str, default="synth/synth_tasks.jsonl")
    parser.add_argument("--n-tasks", type=int, default=200)
    parser.add_argument("--lean-project", type=str, default=None)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--skip-extra-eval", action="store_true",
                        help="Skip evaluating extra test inputs (faster, fewer test cases)")
    args = parser.parse_args()

    script_dir = Path(__file__).resolve().parent.parent
    expressions_path = script_dir / args.expressions
    lean_output = script_dir / args.output_lean
    tasks_output = script_dir / args.output_tasks
    lean_project = Path(args.lean_project) if args.lean_project else script_dir / "env" / "FormalNav"

    print(f"Loading expressions from {expressions_path}")
    expressions = load_expressions(expressions_path)
    print(f"  {len(expressions)} expressions loaded")

    # Select diverse subset
    tasks = select_tasks(expressions, args.n_tasks, seed=args.seed)
    print(f"  {len(tasks)} tasks selected")

    # Distribution
    from collections import Counter
    rt_dist = Counter(t["return_type"] for t in tasks)
    lv_dist = Counter(t["level"] for t in tasks)
    print(f"  Return types: {dict(rt_dist)}")
    print(f"  Levels: {dict(lv_dist)}")

    # Evaluate extra test inputs
    extra_outputs: dict[str, dict[str, str]] = {}
    if not args.skip_extra_eval:
        print(f"\nEvaluating {len(tasks)} expressions on {len(EXTRA_TEST_INPUTS)} extra inputs...")
        extra_outputs = eval_extra_inputs(tasks, lean_project, EXTRA_TEST_INPUTS)
        print(f"  Got extra outputs for {len(extra_outputs)}/{len(tasks)} tasks")

    # Generate Lean file
    lean_content = generate_lean_file(tasks)
    lean_output.parent.mkdir(parents=True, exist_ok=True)
    lean_output.write_text(lean_content)
    print(f"\nLean file: {lean_output} ({len(tasks)} defs)")

    # Generate task JSONL
    task_defs = generate_task_jsonl(tasks, extra_outputs)
    with open(tasks_output, "w") as f:
        for td in task_defs:
            f.write(json.dumps(td) + "\n")
    print(f"Task defs: {tasks_output} ({len(task_defs)} tasks)")

    # Category distribution
    cat_dist = Counter(td["category"] for td in task_defs)
    print(f"Categories: {dict(cat_dist)}")

    # Test case stats
    n_tests = [len(td["test_cases"]) for td in task_defs]
    print(f"Test cases per task: {min(n_tests)}-{max(n_tests)} (avg {sum(n_tests)/len(n_tests):.1f})")


if __name__ == "__main__":
    main()
